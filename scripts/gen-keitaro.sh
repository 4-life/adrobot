#!/usr/bin/env bash
# Generates the Keitaro Pydantic models from backend/app/tracker/keitaro/openapi.yaml.
# models.py is never edited by hand: schema fixes go in models_overrides.py.
#
# Usage: scripts/gen-keitaro.sh [output path, relative to backend/]
#        (default: app/tracker/keitaro/models.py)
set -euo pipefail
cd "$(dirname "$0")/../backend"

OUT="${1:-app/tracker/keitaro/models.py}"

uv run datamodel-codegen \
  --input app/tracker/keitaro/openapi.yaml \
  --input-file-type openapi \
  --output "$OUT" \
  --output-model-type pydantic_v2.BaseModel \
  --target-python-version 3.13 \
  --use-standard-collections \
  --use-union-operator \
  --enum-field-as-literal all \
  --extra-fields allow \
  --allow-population-by-field-name \
  --use-double-quotes \
  --disable-timestamp \
  --custom-file-header "# GENERATED by scripts/gen-keitaro.sh from openapi.yaml - do not edit."

uv run ruff format --quiet "$OUT"
